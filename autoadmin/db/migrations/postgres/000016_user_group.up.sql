-- 用户组：独立于角色的通知/协作分组实体。角色管权限，用户组管"人群"，
-- 后续告警通知接收组等按用户组寻址，避免为收告警而动权限。
--
-- PG 侧差异：MySQL 自增主键 → IDENTITY；MySQL 的 datetime 微秒精度 → timestamp(6)；MySQL 长文本类型 → text；
--   去掉 MySQL 的建表后缀；UNIQUE KEY/KEY → 带名字的约束 + 独立 CREATE INDEX
--   （名字沿用 db/schema/postgres：sys_user_group_name / sys_user_group_member_group_user /
--   idx_user_group_member_user / fk_user_group_member_group / fk_user_group_member_user）；
--   PG 无会话变量 SET @x := (...)，改为按 name 自连接 / 子查询取父菜单 id；
--   INSERT IGNORE → ON CONFLICT DO NOTHING。

CREATE TABLE IF NOT EXISTS sys_user_group (
  id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  create_time timestamp(6) NOT NULL,
  update_time timestamp(6) NOT NULL,
  remark text,
  name varchar(128) NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT sys_user_group_name UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS sys_user_group_member (
  id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  create_time timestamp(6) NOT NULL,
  group_id bigint NOT NULL,
  user_id integer NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT sys_user_group_member_group_user UNIQUE (group_id, user_id),
  CONSTRAINT fk_user_group_member_group FOREIGN KEY (group_id) REFERENCES sys_user_group (id) ON DELETE CASCADE,
  CONSTRAINT fk_user_group_member_user FOREIGN KEY (user_id) REFERENCES sys_user (id) ON DELETE CASCADE
);

CREATE INDEX idx_user_group_member_user ON sys_user_group_member (user_id);

