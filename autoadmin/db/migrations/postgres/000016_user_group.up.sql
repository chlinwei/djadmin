FROM sys_menu user_mgmt
JOIN sys_role_menu rm ON rm.menu_id = user_mgmt.id
JOIN sys_menu ug ON ug.name = '用户组' AND ug.menu_type = 'C'
WHERE user_mgmt.name = '用户管理' AND user_mgmt.menu_type = 'C'
ON CONFLICT DO NOTHING;

