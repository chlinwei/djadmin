-- 问题与证据独立保留，不以扫描、主机或规则删除级联清除整改台账。
ALTER TABLE baseline_scan_result ADD COLUMN rule_key varchar(64) DEFAULT NULL;
CREATE INDEX baseline_result_rule ON baseline_scan_result (host_id, rule_key, scan_id);
CREATE TABLE security_issue (
  id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  host_id bigint NOT NULL,
  host_name varchar(255) NOT NULL,
  host_ip varchar(64) NOT NULL,
  baseline_id bigint NOT NULL,
  item_id bigint NOT NULL,
  rule_key varchar(64) NOT NULL,
  title varchar(255) NOT NULL,
  severity varchar(16) NOT NULL,
  chapter varchar(64) NOT NULL,
  status varchar(16) NOT NULL,
  last_result varchar(16) NOT NULL,
  first_seen timestamp(6) NOT NULL,
  last_seen timestamp(6) NOT NULL,
  last_checked timestamp(6) NOT NULL,
  latest_scan_id bigint NOT NULL,
  occurrence_count bigint NOT NULL DEFAULT 0,
  reopen_count bigint NOT NULL DEFAULT 0,
  closed_at timestamp(6) DEFAULT NULL,
  CONSTRAINT security_issue_identity UNIQUE (host_id, rule_key)
);
CREATE INDEX security_issue_status_time ON security_issue (status, last_checked);
CREATE INDEX security_issue_rule ON security_issue (rule_key);
CREATE INDEX security_issue_severity ON security_issue (severity);
CREATE TABLE security_issue_history (
  id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  issue_id bigint NOT NULL,
  scan_id bigint NOT NULL,
  checked_at timestamp(6) NOT NULL,
  result varchar(16) NOT NULL,
  transition varchar(32) NOT NULL,
  applied boolean NOT NULL,
  expected_value jsonb NOT NULL,
  actual_value jsonb NOT NULL,
  message text NOT NULL,
  remediation text NOT NULL,
  CONSTRAINT security_issue_history_scan UNIQUE (issue_id, scan_id),
  CONSTRAINT security_issue_history_issue_fk FOREIGN KEY (issue_id) REFERENCES security_issue (id)
);
CREATE INDEX security_issue_history_time ON security_issue_history (issue_id, checked_at, scan_id);

