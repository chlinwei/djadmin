  status varchar(16) NOT NULL,
  exit_code integer DEFAULT NULL,
  stdout text NOT NULL,
  stderr text NOT NULL,
  error_message text NOT NULL,
  result_data jsonb NOT NULL,
  host_id bigint DEFAULT NULL,
