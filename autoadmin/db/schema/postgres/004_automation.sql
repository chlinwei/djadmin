  PRIMARY KEY (id),
  CONSTRAINT automation_execution_host_log_host_id_b2ec126e_fk_assets_host_i FOREIGN KEY (host_id) REFERENCES assets_host (id),
  CONSTRAINT automation_execution_host_log_automation_execution_job_id_d6edd FOREIGN KEY (job_id) REFERENCES automation_execution_job (id)
);

