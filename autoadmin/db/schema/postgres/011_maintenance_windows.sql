CREATE INDEX maintenance_delivery_pending ON monitor_alert_notification_event (status, id, update_time);
CREATE TABLE monitor_maintenance_window (
  id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title varchar(200) NOT NULL,
  reason text NOT NULL,
  starts_at timestamp(6) with time zone NOT NULL,
  ends_at timestamp(6) with time zone NOT NULL,
  matchers jsonb NOT NULL,
  status varchar(16) NOT NULL,
  created_by varchar(150) NOT NULL,
  updated_by varchar(150) NOT NULL,
  created_at timestamp(6) with time zone NOT NULL,
  updated_at timestamp(6) with time zone NOT NULL
);
CREATE INDEX maintenance_active ON monitor_maintenance_window (status, ends_at, starts_at);
CREATE TABLE monitor_maintenance_window_audit (
  id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  window_id bigint NOT NULL REFERENCES monitor_maintenance_window(id),
  action varchar(16) NOT NULL,
  actor varchar(150) NOT NULL,
  decided_at timestamp(6) with time zone NOT NULL,
  snapshot jsonb NOT NULL
);
CREATE INDEX maintenance_window_audit_window ON monitor_maintenance_window_audit (window_id);
CREATE TABLE monitor_maintenance_suppression (
  event_id bigint NOT NULL REFERENCES monitor_alert_notification_event(id) ON DELETE CASCADE,
  window_id bigint NOT NULL,
  title varchar(255) NOT NULL,
  ends_at timestamp(6) with time zone NOT NULL,
  decided_at timestamp(6) with time zone NOT NULL,
  PRIMARY KEY (event_id, window_id)
);
CREATE INDEX maintenance_suppression_window ON monitor_maintenance_suppression (window_id);
CREATE TABLE monitor_notification_intent (
  alert_id bigint NOT NULL REFERENCES monitor_alert_history(id) ON DELETE CASCADE,
  event_type varchar(16) NOT NULL,
  PRIMARY KEY (alert_id, event_type)
);
